// Bundles src/lib/auto (pure TypeScript, no dependencies) into a single ES module for
// the auto-inbound and mail-oauth Edge Functions. The output is committed; a unit test fails if it is
// out of date with the source.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTFILES = ['auto-inbound', 'mail-oauth'].map((fn) =>
  join(root, `supabase/functions/${fn}/interpreter.js`)
);
export const BANNER =
  '// GENERATED by scripts/build-edge-interpreter.mjs from src/lib/auto — do not edit.\n';

export async function bundleInterpreter() {
  const result = await build({
    entryPoints: [join(root, 'src/lib/auto/edge.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    legalComments: 'none',
  });
  return BANNER + result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = await bundleInterpreter();
  for (const file of OUTFILES) writeFileSync(file, code);
  console.log('[edge] interpreter.js actualizado');
}
